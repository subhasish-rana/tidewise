export function getTierForPoints(points: number): {
  current: TierDefinition;
  next: TierDefinition | null;
  progressPct: number;
  pointsToNext: number;
} {
  let current = TIERS[0];
  let idx = 0;
  for (let i = 0; i < TIERS.length; i++) {
    if (points >= TIERS[i].minPoints) {
      current = TIERS[i];
      idx = i;
    }
  }
  const next = idx < TIERS.length - 1 ? TIERS[idx + 1] : null;
  if (!next) {
    return { current, next: null, progressPct: 100, pointsToNext: 0 };
  }
  const span = next.minPoints - current.minPoints;
  const gained = points - current.minPoints;
  const progressPct = Math.min(100, Math.max(0, Math.round((gained / span) * 100)));
  return {
    current,
    next,
    progressPct,
    pointsToNext: Math.max(0, next.minPoints - points),
  };
}

